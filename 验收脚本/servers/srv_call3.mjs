import { Client } from "@modelcontextprotocol/sdk/client/index.js";
import { StdioClientTransport } from "@modelcontextprotocol/sdk/client/stdio.js";
const t = new StdioClientTransport({ command: "node", args: ["src/sequentialthinking/dist/index.js"], cwd: process.argv[2] });
const cl = new Client({ name: "seq-smoke", version: "0" });
await cl.connect(t);
const lt = await cl.listTools();
console.log("TOOLS " + lt.tools.map(x => x.name).join(","));
const name = lt.tools[0].name;
const req = lt.tools[0].inputSchema?.required ?? [];
console.log("REQUIRED " + req.join(","));
const args = { thought: "确认工具可执行", thoughtNumber: 2, totalThoughts: 3, nextThoughtNeeded: true };
const r = await cl.callTool({ name, arguments: args });
console.log("RESULT tool=" + name + " isError=" + !!r.isError + " | " + String(r.content?.[0]?.text).replace(/\s+/g, " ").slice(0, 150));
await cl.close();
